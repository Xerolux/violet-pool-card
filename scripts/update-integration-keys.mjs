#!/usr/bin/env node
/**
 * Violet Pool Card – © 2026 Xerolux | MIT License
 *
 * Holt die Entitäts-Schlüssel der Integration und legt sie als Fixture ab.
 *
 * Die Karte schlägt ihre Entitäten über den `translation_key` nach, den die
 * Integration vergibt (siehe `src/utils/entity-registry.ts`). Diese Schlüssel
 * leben in einem anderen Repository — benennt die Integration einen um, würde
 * die Karte die Entität stillschweigend nicht mehr finden.
 *
 * Deshalb liegt hier eine Kopie der Schlüsselliste: `npm test` prüft die
 * Zuordnungstabelle der Karte dagegen, ganz ohne Netz. Die CI ruft dieses
 * Skript vor den Tests auf, damit eine Umbenennung drüben hier rot wird.
 *
 * Aufruf:  npm run keys:update
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE =
  process.env.VIOLET_INTEGRATION_TRANSLATIONS ??
  'https://raw.githubusercontent.com/Xerolux/violet-hass/main/custom_components/violet_pool_controller/translations/en.json';

const TARGET = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'tests',
  'fixtures',
  'integration-entity-keys.json'
);

/**
 * @returns {Promise<Record<string, Record<string, unknown>>>} Die
 *   `entity`-Sektion der Übersetzungsdatei.
 */
async function fetchTranslations() {
  const response = await fetch(SOURCE);
  if (!response.ok) {
    throw new Error(`${SOURCE} lieferte HTTP ${response.status}`);
  }
  const data = await response.json();
  if (!data.entity || typeof data.entity !== 'object') {
    throw new Error(`${SOURCE} enthält keine "entity"-Sektion`);
  }
  return data.entity;
}

const entity = await fetchTranslations();

/** Domain → sortierte Schlüsselliste. */
const keys = Object.fromEntries(
  Object.entries(entity)
    .map(([domain, entries]) => [domain, Object.keys(entries).sort()])
    .sort(([a], [b]) => a.localeCompare(b))
);

const total = Object.values(keys).reduce((sum, list) => sum + list.length, 0);

writeFileSync(
  TARGET,
  `${JSON.stringify(
    {
      _comment:
        'Generated by scripts/update-integration-keys.mjs - do not edit by hand. ' +
        'Entity translation keys of the Violet Pool Controller integration.',
      source: SOURCE,
      keys,
    },
    null,
    2
  )}\n`,
  'utf-8'
);

console.log(`${total} Schlüssel aus ${Object.keys(keys).length} Domains -> ${TARGET}`);
