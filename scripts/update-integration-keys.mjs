#!/usr/bin/env node
/**
 * Violet Pool Card - (c) 2026 Xerolux | MIT License
 *
 * Fetches the integration's entity keys and stores them as a fixture.
 *
 * The card resolves its entities through the `translation_key` the
 * integration assigns (see `src/utils/entity-registry.ts`). Those keys live in
 * a different repository - if the integration renames one, the card would
 * silently stop finding the entity.
 *
 * A copy of the key list therefore lives here: `npm test` checks the card's
 * mapping table against it, entirely offline. CI refreshes the copy with this
 * script before the tests, so a rename over there turns this repository red.
 *
 * Usage:  npm run keys:update
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE =
  process.env.VIOLET_INTEGRATION_TRANSLATIONS ??
  'https://raw.githubusercontent.com/Xerolux/violet-hass/main/custom_components/violet_pool_controller/translations/en.json';

/**
 * The integration's service definitions.
 *
 * `smart_dosing` validates `dosing_type` against its own list and rejects
 * anything else before the handler runs. The card sent the controller's German
 * names (`Chlor`, `Flockmittel`), so chlorine and flocculant dosing could not
 * be triggered at all. The accepted values are copied here for the same reason
 * the entity keys are: so a change over there turns this repository red.
 */
const SERVICES_SOURCE =
  process.env.VIOLET_INTEGRATION_SERVICES ??
  'https://raw.githubusercontent.com/Xerolux/violet-hass/main/custom_components/violet_pool_controller/services.yaml';

const TARGET = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'tests',
  'fixtures',
  'integration-entity-keys.json'
);

/**
 * @returns {Promise<Record<string, Record<string, unknown>>>} The
 *   `entity` section of the translation file.
 */
async function fetchTranslations() {
  const response = await fetch(SOURCE);
  if (!response.ok) {
    throw new Error(`${SOURCE} returned HTTP ${response.status}`);
  }
  const data = await response.json();
  if (!data.entity || typeof data.entity !== 'object') {
    throw new Error(`${SOURCE} has no "entity" section`);
  }
  return data.entity;
}

/**
 * Reads one service's definition out of services.yaml.
 *
 * Only the two things the card has to agree with are taken - which values
 * `dosing_type` accepts and what range `duration` allows - so this stays a
 * few lines of text handling rather than a YAML dependency.
 *
 * @returns {Promise<{dosing_type: string[], duration: {min: number, max: number}}>}
 */
async function fetchSmartDosingService() {
  const response = await fetch(SERVICES_SOURCE);
  if (!response.ok) {
    throw new Error(`${SERVICES_SOURCE} returned HTTP ${response.status}`);
  }
  const yaml = await response.text();

  // From "smart_dosing:" to the next top-level key.
  const block = yaml.match(/^smart_dosing:\n([\s\S]*?)(?=^\S)/m);
  if (!block) {
    throw new Error(`${SERVICES_SOURCE} has no smart_dosing service`);
  }

  const field = block[1].match(/dosing_type:\n([\s\S]*?)(?=^ {4}\S)/m);
  const options = [...(field?.[1] ?? '').matchAll(/^\s*-\s*(\S.*?)\s*$/gm)].map((m) => m[1]);
  if (options.length === 0) {
    throw new Error(`${SERVICES_SOURCE}: smart_dosing has no dosing_type options`);
  }

  const range = block[1].match(/duration:[\s\S]*?min:\s*(\d+)[\s\S]*?max:\s*(\d+)/);
  if (!range) {
    throw new Error(`${SERVICES_SOURCE}: smart_dosing has no duration range`);
  }

  return {
    dosing_type: options,
    duration: { min: Number(range[1]), max: Number(range[2]) },
  };
}

const entity = await fetchTranslations();
const smartDosing = await fetchSmartDosingService();

/** Domain -> sorted list of keys. */
const keys = Object.fromEntries(
  Object.entries(entity)
    .map(([domain, entries]) => [domain, Object.keys(entries).sort()])
    .sort(([a], [b]) => a.localeCompare(b))
);

/**
 * Domain -> key -> the English name.
 *
 * Home Assistant derives an entity id from the English name, so this is what
 * decides how an entity is actually called on an installation. The card needs
 * it for the id it falls back to when the registry cannot resolve an entity,
 * and `tests/entity-registry.test.ts` checks the card's table against it.
 */
const names = Object.fromEntries(
  Object.entries(entity)
    .map(([domain, entries]) => [
      domain,
      Object.fromEntries(
        Object.entries(entries)
          .filter(([, value]) => value && typeof value === 'object' && 'name' in value)
          .map(([key, value]) => [key, value.name])
          .sort(([a], [b]) => a.localeCompare(b))
      ),
    ])
    .sort(([a], [b]) => a.localeCompare(b))
);

const total = Object.values(keys).reduce((sum, list) => sum + list.length, 0);

writeFileSync(
  TARGET,
  `${JSON.stringify(
    {
      _comment:
        'Generated by scripts/update-integration-keys.mjs - do not edit by hand. ' +
        'Entity translation keys of the Violet Pool Controller integration.',
      source: SOURCE,
      services_source: SERVICES_SOURCE,
      keys,
      names,
      services: { smart_dosing: smartDosing },
    },
    null,
    2
  )}\n`,
  'utf-8'
);

console.log(`${total} keys from ${Object.keys(keys).length} Domains -> ${TARGET}`);
