/**
 * Simple i18n helper
 */
export class i18n {
  private static language: Language = 'de';

  static setLanguage(lang: Language): void {
    if (this.language !== lang) {
      this.language = lang;
    }
  }

  static getLanguage(): Language {
    return this.language;
  }

  /**
   * Translate a key, filling `{placeholder}` slots from `params`.
   *
   * Placeholders exist so a sentence stays one string per language. Splitting
   * it around its values and concatenating the parts only works while every
   * language keeps the same word order, which is exactly the assumption that
   * breaks - "Target: 7.2" and "Ziel: 7,2" happen to agree, most do not.
   */
  static t(key: TranslationKey, params?: Record<string, string | number>): string {
    const translations = TRANSLATIONS[this.language];
    // Fall back to English before exposing the raw key to the user
    const text = translations[key as keyof typeof translations] || TRANSLATIONS.en[key] || key;
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, (match, name: string) =>
      // An unknown placeholder stays visible rather than turning into
      // "undefined" - a missing value should look wrong, not plausible.
      name in params ? String(params[name]) : match
    );
  }
}
